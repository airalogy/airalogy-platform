import { expect, test } from "@playwright/test"

test("focused document writing keeps save recovery, scope, navigation and advanced tools accessible", async ({ page }, testInfo) => {
  await page.addInitScript(() => localStorage.setItem("lang", JSON.stringify({ data: "zh-CN", expire: null })))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto("/research-documents")
  const nav = page.getByTestId("workspace-navigation")
  await expect(nav.getByRole("link", { name: "文档", exact: true })).toHaveAttribute("aria-current", "page")
  await expect(page.getByTestId("document-date-filter")).toBeHidden()
  await page.getByTestId("new-research-document").click()
  await expect(page.getByTestId("document-template-source")).toBeHidden()
  await expect(page.getByRole("dialog").getByTestId("document-audience")).toContainText("仅自己可见")
  await page.getByTestId("create-document-confirm").click()
  await expect(nav.getByRole("link", { name: "文档", exact: true })).toHaveAttribute("aria-current", "page")
  await expect(page.getByTestId("document-details")).toBeHidden()
  await expect(page.getByTestId("document-submit")).toBeHidden()
  await expect(page.getByRole("button", { name: "添加字段", exact: true })).toHaveCount(0)
  const prose = page.locator(".ProseMirror[contenteditable=true]")
  await page.getByTestId("document-title").locator("textarea").fill("合成示例：材料稳定性观察")
  await expect(page.getByTestId("document-save-state")).toHaveText("已保存")
  await page.route(/\/api\/research-documents\/[^/]+\/preview$/, route => route.abort("failed"))
  await prose.fill("这是一条用于界面验收的虚构观察。\n记录环境条件、观察过程和下一步安排。")
  await expect(page.getByTestId("document-save-state")).toHaveText("未能保存")
  await expect(prose).toContainText("虚构观察")
  await page.unroute(/\/api\/research-documents\/[^/]+\/preview$/)
  await page.getByTestId("document-save-retry").click()
  await expect(page.getByTestId("document-save-state")).toHaveText("已保存")
  await page.reload()
  await expect(prose).toContainText("虚构观察")
  await page.getByTestId("document-details-toggle").click()
  await expect(page.getByTestId("document-details")).toBeVisible()
  await page.getByTestId("document-details-toggle").click()
  await page.getByTestId("document-more").click()
  await expect(page.getByRole("button", { name: "导出文档", exact: true })).toBeVisible()
  await expect(page.getByTestId("save-as-document-template")).toBeVisible()
  await page.getByTestId("document-more").click()
  await expect(page.getByTestId("save-as-document-template")).toBeHidden()
  await page.screenshot({ path: testInfo.outputPath("document-editor-desktop.png"), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByTestId("workspace-menu-trigger")).toHaveText("文档")
  const title = page.getByTestId("document-title").locator("textarea")
  expect(await title.evaluate(el => el.scrollHeight <= el.clientHeight + 2)).toBeTruthy()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
  await page.screenshot({ path: testInfo.outputPath("document-editor-mobile.png"), fullPage: true })
  await page.getByTestId("document-back").click()
  await expect(page).toHaveURL(/research-documents\?/)
  await expect(page.getByTestId("research-document-link").filter({ hasText: "合成示例：材料稳定性观察" })).toBeVisible()
  await page.goto("/home")
  await page.getByTestId("home-recent-documents").getByRole("link", { name: "合成示例：材料稳定性观察", exact: true }).click()
  await expect(page.getByTestId("document-title").locator("textarea")).toHaveValue("合成示例：材料稳定性观察")
})

test("project document entry inherits its workspace without another destination choice", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("lang", JSON.stringify({ data: "en-US", expire: null })))
  await page.goto("/labs/dev_lab/projects/quickstart/overview")
  await page.getByTestId("new-research-document").click()
  await expect(page.getByRole("dialog").getByTestId("document-audience")).toContainText("Lab Owners/Managers")
  await expect(page.getByTestId("document-template-source")).toBeHidden()
  await page.getByTestId("new-document-title").locator("input").fill("Synthetic Project entry")
  await page.getByTestId("create-document-confirm").click()
  await expect(page.getByTestId("research-document-editor")).toBeVisible()
  await expect(page.getByTestId("research-document-editor").getByTestId("document-audience")).toContainText("Lab Owners/Managers")
  await page.getByTestId("document-back").click()
  await expect(page).toHaveURL(/project_id=/)
  await expect(page.getByTestId("research-document-link").filter({ hasText: "Synthetic Project entry" })).toBeVisible()
})
