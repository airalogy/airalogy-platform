import type { Page } from "@playwright/test"
import { Buffer } from "node:buffer"
import { expect, test } from "@playwright/test"

async function expectVisualToolbarLayout(page: Page) {
  const inputs = page.locator(".aimd-input-tools")
  for (const width of [820, 390, 1440]) {
    await page.setViewportSize({ width, height: 989 })
    await expect(inputs).toHaveCSS("display", "flex")
    const buttons = inputs.locator(":scope > button")
    await expect(buttons).toHaveCount(6)
    for (const button of await buttons.all()) {
      // A flex child computes inline-flex as flex; both preserve icon/label alignment.
      await expect(button).toHaveCSS("display", /^(?:inline-)?flex$/)
      const box = await button.boundingBox()
      expect(box?.height).toBeGreaterThanOrEqual(32)
      expect(box!.x).toBeGreaterThanOrEqual(0)
      expect(box!.x + box!.width).toBeLessThanOrEqual(width)
    }
    const more = inputs.locator("summary")
    await more.click()
    const menu = inputs.locator(".aimd-input-tools__menu")
    await expect(menu).toBeVisible()
    await expect(menu).toHaveCSS("position", "absolute")
    const box = await menu.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(width)
    await more.press("Escape")
    await expect(menu).toBeHidden()
  }
  await inputs.getByRole("button", { name: "Insert text input", exact: true }).click()
  const dialog = page.getByRole("dialog")
  await expect(dialog).toBeVisible()
  await expect(dialog).toHaveCSS("position", "fixed")
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
}

async function insertObservation(page: Page) {
  await page.getByRole("button", { name: "Insert text input", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Insert input", exact: true })
  await dialog.getByText("Advanced settings", { exact: true }).click()
  await dialog.getByLabel("Field ID (generated automatically)", { exact: true }).fill("observation")
  await dialog.getByRole("button", { name: "Insert", exact: true }).click()
}

test("researcher writes without a Protocol, adds a field and submits a revisioned result", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("lang", JSON.stringify({ data: "en-US", expire: null })))
  await page.route(/\/api\/instance(?:\?.*)?$/, async (route) => {
    const response = await route.fetch()
    await route.fulfill({ response, json: { ...await response.json(), ai_enabled: false, enabled_chat_models: [] } })
  })
  await page.goto("/research-documents")
  await page.getByTestId("new-research-document").click()
  await page.getByTestId("create-document-confirm").click()
  await expect(page.getByTestId("research-document-editor")).toBeVisible()
  await expectVisualToolbarLayout(page)
  await page.getByTestId("document-title").locator("textarea").fill("Synthetic research note")
  const prose = page.locator(".ProseMirror[contenteditable=true]")
  await prose.fill("An initial observation without a shared Protocol.")
  await expect(page.getByTestId("document-save-state")).toHaveText("Saved", { timeout: 15000 })
  await page.reload()
  await expect(prose).toContainText("An initial observation")
  await insertObservation(page)
  const value = page.locator("[data-rec-focus-key=\"var:observation\"]")
  await value.fill("Synthetic observation value")
  await expect(page.getByTestId("document-save-state")).toHaveText("Saved", { timeout: 15000 })
  await page.getByTestId("document-results-toggle").click()
  await page.getByTestId("document-submit").click()
  await expect(page.getByRole("dialog")).toContainText("Synthetic observation value")
  await page.getByTestId("document-submit-confirm").click()
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await page.reload()
  await expect(value).toHaveValue("Synthetic observation value")
  await expect(value).toBeEditable()
  await page.getByTestId("document-more").click()
  await page.getByRole("button", { name: "Submitted results", exact: true }).click()
  await expect(page.getByRole("dialog")).toContainText("Synthetic observation value")
  await page.keyboard.press("Escape")
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
  await page.getByTestId("document-more").click()
  await page.getByRole("button", { name: "Repeat this experiment", exact: true }).click()
  await expect(value).toHaveValue("")
})

test("original material is archived without a Protocol and attached to a new note", async ({ page }) => {
  const filename = `synthetic-notes-${Date.now()}.txt`
  await page.addInitScript(() => localStorage.setItem("lang", JSON.stringify({ data: "en-US", expire: null })))
  await page.goto("/research-documents")
  await page.getByRole("tab", { name: "Materials", exact: true }).click()
  await page.getByTestId("material-upload-input").setInputFiles({ name: filename, mimeType: "text/plain", buffer: Buffer.from("Synthetic original observation") })
  await page.getByTestId("material-upload-confirm").click()
  await expect(page.locator(".material-row").filter({ hasText: filename })).toBeVisible()
  const row = page.locator(".material-row").filter({ hasText: filename }).last()
  await row.getByRole("button", { name: "Extract text", exact: true }).click()
  await expect(page.getByRole("dialog").locator("textarea")).toHaveValue("Synthetic original observation")
  await page.getByRole("dialog").getByRole("button", { name: "Create document from this text", exact: true }).click()
  await page.getByTestId("document-details-toggle").click()
  await expect(page.getByTestId("document-details")).toContainText(filename)
  const download = page.waitForEvent("download")
  await page.getByTestId("document-more").click()
  await page.getByRole("button", { name: "Export document", exact: true }).click()
  expect((await download).suggestedFilename()).toBe("research-document.zip")
})

