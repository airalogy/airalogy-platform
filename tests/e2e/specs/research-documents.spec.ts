test("templates can be copied into Lab and Project scopes and archived without changing documents", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("lang", JSON.stringify({ data: "en-US", expire: null })))
  await page.goto("/research-documents?tab=templates")
  await page.getByTestId("new-document-template").click()
  await page.getByTestId("template-title").locator("input").fill("Synthetic scope starter")
  await page.getByTestId("template-save").click()
  await page.getByTestId("template-save").click()
  let row = page.locator("article").filter({ hasText: "Synthetic scope starter" })
  for (const prefix of ["Lab", "Project"]) {
    await row.getByRole("button", { name: "Copy to a scope", exact: true }).click()
    const scopeSelect = page.getByTestId("template-scope")
    const value = await scopeSelect.locator("option").filter({ hasText: new RegExp(`^${prefix} ·`) }).first().getAttribute("value")
    await scopeSelect.selectOption(value!)
    await page.getByTestId("template-title").locator("input").fill(`Synthetic ${prefix} starter`)
    await page.getByTestId("template-save").click()
    await page.getByTestId("template-save").click()
    row = page.locator("article").filter({ hasText: `Synthetic ${prefix} starter` })
    await expect(row).toBeVisible()
  }
  await row.getByRole("button", { name: "Archive", exact: true }).click()
  await page.getByRole("button", { name: "Confirm", exact: true }).click()
  await expect(row).toHaveCount(0)
  await page.getByRole("checkbox", { name: "Show archived", exact: true }).check()
  await expect(row).toBeVisible()
  await row.getByRole("button", { name: "Restore", exact: true }).click()
  await page.getByRole("button", { name: "Confirm", exact: true }).click()
  await expect(row).toHaveCount(0)
  await page.getByRole("checkbox", { name: "Show archived", exact: true }).uncheck()
  await expect(row).toBeVisible()
})
